func TestMainnetGenesisCarriesMainnetIdentity(t *testing.T) {
	res, a := buildMainnet(t)

	require.Equal(t, "hashgram-1", res.ChainID)
	require.Equal(t, "hashgram-mainnet", res.NetworkID)

	var network networktypes.GenesisState
	a.AppCodec().MustUnmarshalJSON(res.AppState[networktypes.ModuleName], &network)

	require.Equal(t, "hashgram-mainnet", network.Info.NetworkId)
	require.Equal(t, "hashgram-1", network.Info.ChainId)
	require.Equal(t, "HGM1", string(network.Info.NetworkMagic))
	require.NoError(t, network.Validate())

	// Every fork-isolation check must be on.
	require.Equal(t, networktypes.StrictForkIsolation(), network.ForkIsolation)
}

// TestDevnetGenesisIsNotMainnet: a devnet must never be able to claim to be
// Mainnet.
func TestDevnetGenesisIsNotMainnet(t *testing.T) {
	a := app.NewHashgramApp(
		log.NewNopLogger(), dbm.NewMemDB(), nil, true,
		simtestutil.NewAppOptionsWithFlagHome(t.TempDir()),
	)

	res, err := genesis.Build(a.AppCodec(), a.DefaultGenesis(), genesis.Config{
		FounderAddress: founderAddress(),
		Devnet:         true,
		GenesisTime:    time.Unix(1_700_000_000, 0).UTC(),
	})
	require.NoError(t, err)

	require.Equal(t, "hashgram-devnet-1", res.ChainID)
	require.Equal(t, "hashgram-devnet", res.NetworkID)

	var network networktypes.GenesisState
	a.AppCodec().MustUnmarshalJSON(res.AppState[networktypes.ModuleName], &network)
	require.Equal(t, "HGD1", string(network.Info.NetworkMagic))

	// Supply is identical: a devnet models the real tokenomics.
	require.Equal(t, "1000000000000000uhash", res.TotalSupply.String())
}

