// TestFounderRevenueBeneficiaryIsTheSuppliedAddress is §16: the beneficiary
// is the address the operator supplied, at exactly 1%.
func TestFounderRevenueBeneficiaryIsTheSuppliedAddress(t *testing.T) {
	res, a := buildMainnet(t)

	var founder foundertypes.GenesisState
	a.AppCodec().MustUnmarshalJSON(res.AppState[foundertypes.ModuleName], &founder)

	require.Equal(t, founderAddress(), founder.Params.Beneficiary)
	require.Equal(t, uint32(100), founder.Params.FeeBasisPoints)
	require.Equal(t, "1.00%", founder.Params.FeePercent())

	// Nothing has accrued or been paid on a fresh chain.
	require.True(t, founder.Ledger.TotalAccrued.IsZero())
	require.True(t, founder.Ledger.TotalPaid.IsZero())

	// The genesis file carries no beneficiary history. The audit trail's
	// first entry is written by x/founder's InitGenesis at chain start, from
	// the configured beneficiary, so it records the height at which the
	// chain actually began rather than a value copied from a file.
	require.Empty(t, founder.BeneficiaryHistory)
	require.NoError(t, founder.Validate())
}

