// TestGenesisIsDeterministic is what makes the genesis hash a usable network
// identifier: two operators with the same inputs must produce byte-identical
// files.
func TestGenesisIsDeterministic(t *testing.T) {
	build := func() []byte {
		a := app.NewHashgramApp(
			log.NewNopLogger(), dbm.NewMemDB(), nil, true,
			simtestutil.NewAppOptionsWithFlagHome(t.TempDir()),
		)
		res, err := genesis.Build(a.AppCodec(), a.DefaultGenesis(), genesis.Config{
			FounderAddress: founderAddress(),
			GenesisTime:    time.Unix(1_700_000_000, 0).UTC(),
		})
		require.NoError(t, err)

		out, err := json.Marshal(res.AppState)
		require.NoError(t, err)
		return out
	}

	first := build()
	second := build()
	require.Equal(t, string(first), string(second),
		"two builds with identical inputs produced different genesis app state")
}

// TestGenesisTimeIsTruncatedToTheSecond: a sub-second component would make
// two runs differ and produce different genesis hashes.
func TestGenesisTimeIsTruncatedToTheSecond(t *testing.T) {
	a := app.NewHashgramApp(
		log.NewNopLogger(), dbm.NewMemDB(), nil, true,
		simtestutil.NewAppOptionsWithFlagHome(t.TempDir()),
	)

	buildAt := func(ts time.Time) []byte {
		res, err := genesis.Build(a.AppCodec(), a.DefaultGenesis(), genesis.Config{
			FounderAddress: founderAddress(),
			GenesisTime:    ts,
		})
		require.NoError(t, err)
		out, err := json.Marshal(res.AppState)
		require.NoError(t, err)
		return out
	}

	base := time.Unix(1_700_000_000, 0).UTC()
	withNanos := base.Add(123456 * time.Microsecond)

	require.Equal(t, string(buildAt(base)), string(buildAt(withNanos)),
		"a sub-second genesis time changed the output")
}

