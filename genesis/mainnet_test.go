// TestTotalSupplyIsExactlyOneBillion is §116.1 at the genesis layer: the sum
// of every genesis balance must be exactly 1,000,000,000 HASH.
func TestTotalSupplyIsExactlyOneBillion(t *testing.T) {
	res, a := buildMainnet(t)

	want := sdk.NewCoins(sdk.NewCoin(hgparams.BaseCoinDenom, hgparams.MaxSupplyBase()))
	require.Equal(t, want.String(), res.TotalSupply.String())
	require.Equal(t, "1000000000000000uhash", res.TotalSupply.String())

	// And the bank genesis agrees with the sum of its own balances.
	var bank banktypes.GenesisState
	a.AppCodec().MustUnmarshalJSON(res.AppState[banktypes.ModuleName], &bank)

	sum := sdk.NewCoins()
	for _, b := range bank.Balances {
		sum = sum.Add(b.Coins...)
	}
	require.Equal(t, want.String(), sum.String())
	require.Equal(t, want.String(), bank.Supply.String())
}

// TestAllocationsMatchTheDistributionTable checks each documented allocation
// lands where §13 says it should.
func TestAllocationsMatchTheDistributionTable(t *testing.T) {
	res, a := buildMainnet(t)

	var bank banktypes.GenesisState
	a.AppCodec().MustUnmarshalJSON(res.AppState[banktypes.ModuleName], &bank)

	balanceOf := func(addr string) sdk.Coins {
		for _, b := range bank.Balances {
			if b.Address == addr {
				return b.Coins
			}
		}
		return sdk.NewCoins()
	}

	hash := func(n int64) string {
		return sdk.NewCoins(sdk.NewCoin(hgparams.BaseCoinDenom, hgparams.HashToBase(n))).String()
	}

	// Founder: 200,000,000 HASH.
	require.Equal(t, hash(200_000_000), balanceOf(founderAddress()).String(),
		"the Founder allocation is not 200,000,000 HASH")

	// Useful-service reserve: 500,000,000 HASH.
	require.Equal(t, hash(500_000_000),
		balanceOf(authtypes.NewModuleAddress(serviceprooftypes.ModuleName).String()).String())

	// Welcome pool: 1,850,000 HASH.
	require.Equal(t, hash(1_850_000),
		balanceOf(authtypes.NewModuleAddress(welcometypes.ModuleName).String()).String())

	// Treasury reserves.
	for name, amount := range map[string]int64{
		treasurytypes.ReserveTreasury:  150_000_000,
		treasurytypes.ReserveDevGrants: 50_000_000,
		treasurytypes.ReserveLiquidity: 50_000_000,
		// Growth less the welcome pool.
		treasurytypes.ReserveGrowth: 50_000_000 - 1_850_000,
	} {
		require.Equal(t, hash(amount),
			balanceOf(treasurytypes.ReserveAddress(name).String()).String(),
			"reserve %q", name)
	}
}

// TestEveryAllocationHasAnAddress: §13 requires all allocations to be
// transparently visible on chain, which means each must have an address a
// bank query can be pointed at.
func TestEveryAllocationHasAnAddress(t *testing.T) {
	res, _ := buildMainnet(t)

	require.NotEmpty(t, res.Allocations)
	seen := map[string]bool{}
	for _, a := range res.Allocations {
		require.NotEmpty(t, a.Address, "allocation %q has no address", a.Name)
		require.NotEmpty(t, a.Description, "allocation %q has no description", a.Name)
		require.False(t, a.Amount.IsZero(), "allocation %q is empty", a.Name)

		_, err := sdk.AccAddressFromBech32(a.Address)
		require.NoError(t, err, "allocation %q address is malformed", a.Name)

		require.False(t, seen[a.Address], "two allocations share the address %s", a.Address)
		seen[a.Address] = true
	}
}

