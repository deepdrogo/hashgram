// TestFounderVestingIsTwentyMillionUnlockedAndOneEightyVested is §14: the
// Founder holds 200M of which 20M is spendable at genesis and 180M vests.
func TestFounderVestingIsTwentyMillionUnlockedAndOneEightyVested(t *testing.T) {
	res, a := buildMainnet(t)

	var auth authtypes.GenesisState
	a.AppCodec().MustUnmarshalJSON(res.AppState[authtypes.ModuleName], &auth)

	accounts, err := authtypes.UnpackAccounts(auth.Accounts)
	require.NoError(t, err)

	var founder *vestingtypes.PeriodicVestingAccount
	for _, acc := range accounts {
		if acc.GetAddress().String() != founderAddress() {
			continue
		}
		pva, ok := acc.(*vestingtypes.PeriodicVestingAccount)
		require.True(t, ok, "the Founder account is %T, expected a PeriodicVestingAccount", acc)
		founder = pva
	}
	require.NotNil(t, founder, "no Founder account in genesis")

	// original_vesting is the locked part.
	require.Equal(t, hgparams.HashToBase(180_000_000).String(),
		founder.OriginalVesting.AmountOf(hgparams.BaseCoinDenom).String(),
		"the locked portion is not 180,000,000 HASH")

	// The periods must sum to exactly the locked amount: equal monthly
	// amounts with the truncation remainder in the final period, not
	// 180,000,000 minus accumulated rounding.
	total := math.ZeroInt()
	for _, p := range founder.VestingPeriods {
		total = total.Add(p.Amount.AmountOf(hgparams.BaseCoinDenom))
	}
	require.Equal(t, founder.OriginalVesting.AmountOf(hgparams.BaseCoinDenom).String(), total.String(),
		"the vesting periods do not sum to the locked amount")

	require.Len(t, founder.VestingPeriods, 96, "8 years of monthly periods")

	// The spendable-at-genesis part is total balance minus locked.
	var bank banktypes.GenesisState
	a.AppCodec().MustUnmarshalJSON(res.AppState[banktypes.ModuleName], &bank)
	var founderBalance sdk.Coins
	for _, b := range bank.Balances {
		if b.Address == founderAddress() {
			founderBalance = b.Coins
		}
	}
	unlocked, negative := founderBalance.SafeSub(founder.OriginalVesting...)
	require.False(t, negative)
	require.Equal(t, hgparams.HashToBase(20_000_000).String(),
		unlocked.AmountOf(hgparams.BaseCoinDenom).String(),
		"the amount spendable at genesis is not 20,000,000 HASH")
}

// TestNoHiddenAdditionalFounderMint is §95: exactly one account holds the
// Founder allocation, and nothing else is credited to the Founder address.
func TestNoHiddenAdditionalFounderMint(t *testing.T) {
	res, a := buildMainnet(t)

	var bank banktypes.GenesisState
	a.AppCodec().MustUnmarshalJSON(res.AppState[banktypes.ModuleName], &bank)

	count := 0
	total := sdk.NewCoins()
	for _, b := range bank.Balances {
		if b.Address == founderAddress() {
			count++
			total = total.Add(b.Coins...)
		}
	}
	require.Equal(t, 1, count, "the Founder address appears in %d genesis balances", count)
	require.Equal(t, hgparams.HashToBase(200_000_000).String(),
		total.AmountOf(hgparams.BaseCoinDenom).String(),
		"the Founder holds more than the 200,000,000 HASH allocation")
}

