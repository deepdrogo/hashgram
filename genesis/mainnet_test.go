// founderAddress is a DEVNET-only address standing in for the Founder's
// public address. Derived from label bytes so it is always a valid checksum
// and so nothing in the repository looks like an address with a key behind it.
func founderAddress() string {
	b := make([]byte, 20)
	copy(b, "DEVNET-FOUNDER-ADDR")
	return sdk.AccAddress(b).String()
}

func buildMainnet(t *testing.T) (*genesis.Result, *app.HashgramApp) {
	t.Helper()

	a := app.NewHashgramApp(
		log.NewNopLogger(), dbm.NewMemDB(), nil, true,
		simtestutil.NewAppOptionsWithFlagHome(t.TempDir()),
	)

	res, err := genesis.Build(a.AppCodec(), a.DefaultGenesis(), genesis.Config{
		FounderAddress: founderAddress(),
		GenesisTime:    time.Unix(1_700_000_000, 0).UTC(),
	})
	require.NoError(t, err)
	return res, a
}

